import fs from 'fs';
import path from 'path';

export interface BlogPost {
  slug: string;
  title: string;
  excerpt: string;
  date: string;
  readingTime: string;
  category: string;
  image: string;
  author: string;
}

const CONTENT_DIR = path.join(process.cwd(), 'content', 'blog');

function parseFrontmatter(raw: string): Record<string, string> {
  const data: Record<string, string> = {};
  if (raw.startsWith('---')) {
    const end = raw.indexOf('---', 3);
    if (end !== -1) {
      const block = raw.slice(3, end);
      for (const line of block.split('\n')) {
        const idx = line.indexOf(':');
        if (idx > 0) {
          const key = line.slice(0, idx).trim();
          let val = line.slice(idx + 1).trim();
          val = val.replace(/^["']|["']$/g, '');
          data[key] = val;
        }
      }
    }
  }
  return data;
}

function toPost(file: string, meta: Record<string, string>, content: string): BlogPost {
  const wordCount = content.split(/\s+/).length;
  const readTime = Math.max(1, Math.ceil(wordCount / 200));
  const base = path.basename(file, '.md');
  const excerpt =
    meta.excerpt ??
    content
      .replace(/^---[\s\S]*?---/, '')
      .replace(/^#+\s+.*/gm, '')
      .replace(/!\[.*?\]\(.*?\)/, '')
      .trim()
      .slice(0, 220);

  return {
    slug: meta.slug ?? base,
    title: meta.title ?? base.replace(/-/g, ' '),
    excerpt,
    date: meta.date ?? '',
    readingTime: `${readTime} min`,
    category: meta.category ?? 'Geral',
    image: meta.image ?? `/images/blog/${base}.png`,
    author: meta.author ?? 'Dr. Herlon Moura',
  };
}

// Server/node only — reads markdown from disk.
export function loadBlogPosts(): BlogPost[] {
  if (!fs.existsSync(CONTENT_DIR)) return [];

  const files = fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith('.md'));
  return files
    .map((file) => {
      const raw = fs.readFileSync(path.join(CONTENT_DIR, file), 'utf-8');
      return toPost(file, parseFrontmatter(raw), raw);
    })
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
}

export function getPostBySlug(slug: string): BlogPost | null {
  const posts = loadBlogPosts();
  return posts.find((p) => p.slug === slug) ?? null;
}

// Regenerates lib/blog-data.generated.ts (a plain, fs-free data module that
// client components can import). Run via `npm run blog:gen`.
export function generateBlogData(): void {
  const posts = loadBlogPosts();
  const target = path.join(process.cwd(), 'lib', 'blog-data.generated.ts');
  const body =
    `// AUTO-GENERATED by npm run blog:gen — do not edit by hand.\n` +
    `// Plain data module: safe to import from 'use client' components.\n` +
    `import type { BlogPost } from './blog';\n\n` +
    `export const BLOG_POSTS: BlogPost[] = ${JSON.stringify(posts, null, 2)};\n`;
  fs.writeFileSync(target, body);
}

// When executed directly (node lib/blog.ts), regenerate the data file.
if (require.main === module) {
  generateBlogData();
  console.log(`Generated ${loadBlogPosts().length} posts → lib/blog-data.generated.ts`);
}
